_FALLBACK_LANG = "tr"


def get_lang():
    from db import get_setting

    lang = (get_setting("language") or "tr-TR").split("-")[0].strip().lower()
    return lang if lang in LANGS else _FALLBACK_LANG


def t(key, **kw):
    """Anahtara karsilik gelen ceviri metnini dondurur; eksikse Turkce fallback."""
    entry = TEMPLATES.get(key)
    if not entry:
        return key
    tpl = entry.get(get_lang()) or entry.get(_FALLBACK_LANG) or ""
    if kw:
        try:
            return tpl.format(**kw)
        except (KeyError, IndexError, ValueError):
            return tpl
    return tpl
